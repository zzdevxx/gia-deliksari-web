#!/usr/bin/env node
/**
 * Generate a SQL restore file from a JSON snapshot.
 *
 * Why this exists: the backup job produced JSON snapshots for weeks, but there
 * was NO script that could turn one back into a database. A backup with no
 * tested restore path is not a backup — it is a file. This closes that loop.
 *
 * Usage:
 *   node scripts/restore-d1-from-snapshot.mjs backups/d1/<file>.json > restore.sql
 *   npx wrangler d1 execute <target-db> --remote --file=restore.sql
 *
 * Safety: this only WRITES a .sql file to stdout. It never touches a database
 * itself, so the generated SQL can be read and reviewed before it is applied.
 * That matters for a drill against real congregation data.
 *
 * Deliberately generates plain INSERT statements (not INSERT OR REPLACE) so a
 * restore into a non-empty database fails loudly on a primary-key clash rather
 * than silently overwriting rows.
 */
import fs from 'node:fs';
import path from 'node:path';

const snapshotPath = process.argv[2];

if (!snapshotPath) {
  console.error('Usage: node scripts/restore-d1-from-snapshot.mjs <snapshot.json>');
  process.exit(1);
}
if (!fs.existsSync(snapshotPath)) {
  console.error(`FATAL: snapshot not found: ${snapshotPath}`);
  process.exit(1);
}

/**
 * Snapshot key → real D1 table name.
 *
 * `youth_balance` is absent on purpose: in the schema it is a VIEW computed
 * from youth_treasury_transactions, so it has no rows and cannot be inserted
 * into. Restoring the transactions restores the balance by definition.
 */
const TABLE_MAP = {
  youth_treasury: 'youth_treasury_transactions',
  announcements: 'announcements',
  servant_rosters: 'servant_rosters',
  inventory_items: 'inventory_items',
  sermons: 'sermons',
  gallery_items: 'gallery_items',
  ministry_requests: 'ministry_requests',
  users: 'users',
  audit_log: 'audit_log',
};

/** Quote an identifier for SQLite. Doubling `"` is the escape. */
function ident(name) {
  return `"${String(name).replace(/"/g, '""')}"`;
}

/** Quote a value for SQLite. Doubling `'` is the escape; no backslash escapes. */
function literal(value) {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'boolean') return value ? '1' : '0';
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) return 'NULL';
    return String(value);
  }
  if (typeof value === 'object') {
    // D1 columns holding JSON arrive as parsed objects in some driver paths.
    return `'${JSON.stringify(value).replace(/'/g, "''")}'`;
  }
  return `'${String(value).replace(/'/g, "''")}'`;
}

const snapshot = JSON.parse(fs.readFileSync(snapshotPath, 'utf8'));
const tables = snapshot.tables ?? {};
const exportedAt = snapshot._meta?.exported_at ?? 'unknown';

const out = [];
out.push('-- Generated by scripts/restore-d1-from-snapshot.mjs');
out.push(`-- Source snapshot : ${path.basename(snapshotPath)}`);
out.push(`-- Exported at     : ${exportedAt}`);
out.push(`-- Target          : LOOK AT THE COMMAND YOU RUN THIS WITH`);
out.push('--');
out.push('-- Review before applying. Generated as plain INSERTs, so a restore into a');
out.push('-- non-empty database fails on a primary-key clash instead of overwriting.');
out.push('');
// No BEGIN/COMMIT: D1 rejects `BEGIN TRANSACTION` in a .sql file
// ("please use the state.storage.transaction() APIs instead"). Each statement
// runs on its own, which is fine for a restore into an empty database — the
// file is applied to a fresh D1, not to a live one. Wrangler's --file path
// batches the statements it can.
out.push('PRAGMA foreign_keys = OFF;');
out.push('');

/**
 * Columns the snapshot deliberately omits but the schema requires.
 *
 * `users.password_hash` is redacted by the backup script on purpose — a backup
 * file should not carry password material. But the column is NOT NULL, so a
 * faithful restore of the snapshot alone fails with
 * "NOT NULL constraint failed: users.password_hash".
 *
 * The placeholder below is a valid bcrypt-format string that will never match
 * any password, so every restored account is inert until an operator resets it.
 * That is the correct failure mode: a restored portal must not silently accept
 * a known credential. The drill exists precisely to surface this, and the
 * restore output states it plainly rather than hiding it.
 */
const PLACEHOLDER_BCRYPT = '$2b$10$0000000000000000000000000000000000000000000000000000X';
const REDACTED_REQUIRED = {
  users: { password_hash: PLACEHOLDER_BCRYPT },
};

let totalRows = 0;
const summary = [];
const warnings = [];

for (const [snapshotKey, table] of Object.entries(TABLE_MAP)) {
  const rows = tables[snapshotKey];
  if (!Array.isArray(rows) || rows.length === 0) {
    summary.push(`--  ${table.padEnd(30)} 0 rows (nothing to restore)`);
    continue;
  }

  // Union of keys across rows: a sparse row must not misalign the column list.
  const columns = Array.from(
    rows.reduce((set, row) => {
      Object.keys(row ?? {}).forEach((k) => set.add(k));
      return set;
    }, new Set()),
  );

  // Fill in required-but-redacted columns and say so.
  const placeholders = REDACTED_REQUIRED[table];
  if (placeholders) {
    for (const [col, value] of Object.entries(placeholders)) {
      if (!columns.includes(col)) {
        columns.push(col);
        warnings.push(
          `${table}.${col} was not in the snapshot (redacted for safety); ` +
            `filled with an inert placeholder — reset it after restoring`,
        );
      }
    }
  }

  if (columns.length === 0) {
    summary.push(`--  ${table.padEnd(30)} ${rows.length} rows (all empty objects, skipped)`);
    continue;
  }

  out.push(`-- ${table}: ${rows.length} rows`);
  const colList = columns.map(ident).join(', ');
  for (const row of rows) {
    const values = columns.map((c) => {
      const fromRow = row?.[c];
      if (fromRow !== undefined) return literal(fromRow);
      const fill = placeholders?.[c];
      return fill !== undefined ? literal(fill) : literal(fromRow);
    });
    out.push(`INSERT INTO ${ident(table)} (${colList}) VALUES (${values.join(', ')});`);
  }
  out.push('');

  totalRows += rows.length;
  summary.push(`--  ${table.padEnd(30)} ${rows.length} rows`);
}

out.push('PRAGMA foreign_keys = ON;');

// Summary goes to stderr so stdout stays a clean, pipeable .sql file.
console.error('Restore plan:');
console.error(`  source: ${snapshotPath}`);
console.error(`  exported: ${exportedAt}`);
if (warnings.length > 0) {
  console.error('');
  console.error('  !! ATTENTION:');
  warnings.forEach((w) => console.error(`     - ${w}`));
  console.error('');
}
summary.forEach((line) => console.error(line.replace(/^--\s?/, '  ')));
console.error(`  TOTAL: ${totalRows} rows`);

if (totalRows === 0) {
  console.error('\nFATAL: snapshot contains 0 rows. Refusing to emit a restore file.');
  process.exit(1);
}

process.stdout.write(out.join('\n') + '\n');
